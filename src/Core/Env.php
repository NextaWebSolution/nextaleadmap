<?php

declare(strict_types=1);

namespace App\Core;

/** Minimal, safe .env reader (no variable expansion, no code execution). */
final class Env
{
    private static array $vars = [];

    public static function load(string $file): void
    {
        self::$vars = [];
        if (!is_file($file) || !is_readable($file)) {
            return;
        }
        foreach (file($file, FILE_IGNORE_NEW_LINES) ?: [] as $line) {
            $line = trim($line);
            if ($line === '' || $line[0] === '#' || !str_contains($line, '=')) {
                continue;
            }
            [$k, $v] = explode('=', $line, 2);
            $k = trim($k);
            if (!preg_match('/^[A-Z][A-Z0-9_]*$/', $k)) {
                continue;
            }
            $v = trim($v);
            if (strlen($v) >= 2 && ($v[0] === '"' || $v[0] === "'") && $v[-1] === $v[0]) {
                $q = $v[0];
                $v = substr($v, 1, -1);
                if ($q === '"') {
                    $v = str_replace(['\\n', '\\"', '\\\\'], ["\n", '"', '\\'], $v);
                }
            }
            self::$vars[$k] = $v;
        }
    }

    public static function get(string $key, ?string $default = null): ?string
    {
        $v = self::$vars[$key] ?? null;
        return ($v === null || $v === '') ? $default : $v;
    }

    public static function bool(string $key, bool $default = false): bool
    {
        $v = self::get($key);
        return $v === null ? $default : in_array(strtolower($v), ['1', 'true', 'yes', 'on'], true);
    }

    /**
     * Fail-closed startup validation for an installed application. Returns problems (never secret values).
     * @return list<string>
     */
    public static function configErrors(): array
    {
        $errors = [];
        $raw = (string) self::get('APP_KEY', '');
        $key = base64_decode(str_starts_with($raw, 'base64:') ? substr($raw, 7) : $raw, true);
        if ($key === false || strlen($key) !== 32) {
            $errors[] = 'APP_KEY is missing or not 32 bytes (base64).';
        }
        foreach (['DB_HOST', 'DB_DATABASE', 'DB_USERNAME'] as $k) {
            if (self::get($k) === null) {
                $errors[] = "$k is not set.";
            }
        }
        $url = (string) self::get('APP_URL', '');
        if ($url === '' || !filter_var($url, FILTER_VALIDATE_URL) || !preg_match('#^https?://#i', $url)) {
            $errors[] = 'APP_URL must be the full http(s):// address of the app.';
        }
        return $errors;
    }

    /** Serialise key/values into .env text with safe quoting. */
    public static function render(array $values): string
    {
        $out = "# Generated by the NextaLeadMap installer on " . gmdate('Y-m-d H:i') . " UTC.\n"
            . "# Keep this file private. Updates never overwrite it.\n";
        foreach ($values as $k => $v) {
            $v = (string) $v;
            if ($v !== '' && preg_match('/[\s#"\'\\\\=]/', $v)) {
                $v = '"' . str_replace(['\\', '"', "\n"], ['\\\\', '\\"', '\\n'], $v) . '"';
            }
            $out .= $k . '=' . $v . "\n";
        }
        return $out;
    }
}
